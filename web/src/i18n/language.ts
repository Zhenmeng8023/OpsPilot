const messages: Record<Language, Record<string, string>> = {
  zh: { ...en, ...zh },
  en
};

function formatMessage(template: string, params?: TemplateParams) {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

function createTranslator(language: Language) {
  return (key: MessageKey, params?: TemplateParams) => formatMessage(messages[language][key] ?? key, params);
}

interface LanguageState {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: MessageKey, params?: TemplateParams) => string;
}

export const useLanguageStore = create<LanguageState>((set, get) => {
  const initialLanguage = resolveInitialLanguage();
  applyDocumentLanguage(initialLanguage);

  return {
    language: initialLanguage,
    setLanguage: (language) => {
      localStorage.setItem(LANGUAGE_KEY, language);
      applyDocumentLanguage(language);
      set({ language, t: createTranslator(language) });
    },
    toggleLanguage: () => {
      const next = get().language === "zh" ? "en" : "zh";
      get().setLanguage(next);
    },
    t: createTranslator(initialLanguage)
  };
});

function resolveInitialLanguage(): Language {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  if (saved === "zh" || saved === "en") {
    return saved;
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function applyDocumentLanguage(language: Language) {
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.language = language;
}
