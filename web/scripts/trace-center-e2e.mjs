async function api(endpoint, options = {}) {
  const headers = new Headers();
  headers.set("Content-Type", "application/json");
  if (options.token && !options.skipAuth) {
    headers.set("Authorization", `Bearer ${options.token}`);
  }
  const response = await fetch(`${apiBaseURL}${endpoint}`, {
    method: options.method ?? "GET",
    headers,
    body: options.body === undefined ? undefined : JSON.stringify(options.body)
  });
  const body = await response.json();
  if (!response.ok || body.code !== 0) {
    throw new Error(`${options.method ?? "GET"} ${endpoint} failed: status=${response.status} code=${body.code} message=${body.message}`);
  }
  return body;
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function percentile(values, percentileValue) {
  if (values.length === 0) {
    return 0;
  }
  const sorted = [...values].sort((left, right) => left - right);
  const index = Math.min(sorted.length - 1, Math.ceil(sorted.length * percentileValue) - 1);
  return sorted[index];
}

async function waitForWorkflowRunStatus(runId, token, expectedStatuses, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const run = await api(`/api/v1/workflow-runs/${encodeURIComponent(runId)}`, { token });
    if (expectedStatuses.includes(run.data.status)) {
      return run.data;
    }
    await new Promise((resolve) => setTimeout(resolve, 500));
  }
  throw new Error(`Workflow run ${runId} did not reach [${expectedStatuses.join(", ")}] within ${timeoutMs}ms.`);
}
