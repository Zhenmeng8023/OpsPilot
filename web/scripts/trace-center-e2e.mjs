const traceLookupIterations = Number(process.env.TRACE_E2E_LOOKUPS ?? "20");
const traceP95ThresholdMs = Number(process.env.TRACE_E2E_P95_MS ?? "1000");

await mkdir(artifactDir, { recursive: true });

const session = await api("/api/v1/auth/login", {
  method: "POST",
  skipAuth: true,
  body: { username, password }
});
