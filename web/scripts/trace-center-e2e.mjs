import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright";

const webBaseURL = process.env.SMOKE_BASE_URL ?? "http://127.0.0.1:5174";
const apiBaseURL = process.env.SMOKE_API_BASE_URL ?? process.env.VITE_API_BASE_URL ?? "http://127.0.0.1:18889";
const username = process.env.SMOKE_USERNAME ?? "admin";
const password = process.env.SMOKE_PASSWORD ?? "Admin@123456";
